#!/usr/bin/env node
// Writes the help-article catalog the sentry-triage Worker matches feedback against
// (#3275). A Worker cannot read `website/` at runtime, so it bundles a SNAPSHOT:
// every help article's slug, title and description, plus a content hash
// (`catalogVersion`) that each match post carries, so a pick made against a stale
// snapshot is visible in Discord rather than silent.
//
// Run after adding, removing or retitling a help article, then redeploy the Worker:
//   node website/scripts/generate-help-article-catalog.mjs
//
// Dependency-free on purpose: it runs from a bare checkout with no npm install.
// It reads only the `title:` and `description:` frontmatter lines, which every help
// article writes as one double-quoted string, and fails loudly on any article that
// does not, rather than bundling a partial catalog.

import { createHash } from "node:crypto";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const helpDir = join(repoRoot, "website/src/content/help");
const outFile = join(repoRoot, "workers/sentry-triage/src/articleCatalog.js");

function frontmatterField(source, field, file) {
  const block = source.match(/^---\n([\s\S]*?)\n---/);
  if (!block) throw new Error(`${file}: no frontmatter block`);
  const line = block[1].split("\n").find((l) => l.startsWith(`${field}:`));
  if (!line) throw new Error(`${file}: missing ${field}`);
  const raw = line.slice(field.length + 1).trim();
  let value;
  try {
    value = JSON.parse(raw);
  } catch {
    throw new Error(`${file}: ${field} is not one double-quoted string: ${raw}`);
  }
  if (typeof value !== "string" || !value.trim()) {
    throw new Error(`${file}: ${field} is empty`);
  }
  return value;
}

const files = readdirSync(helpDir).filter((f) => f.endsWith(".md")).sort();
if (files.length === 0) throw new Error(`no help articles found in ${helpDir}`);

const articles = files.map((file) => {
  const source = readFileSync(join(helpDir, file), "utf8");
  if (/^draft:\s*true\s*$/m.test(source.split(/\n---\n/)[0])) return null;
  return {
    slug: file.replace(/\.md$/, ""),
    title: frontmatterField(source, "title", file),
    description: frontmatterField(source, "description", file),
  };
}).filter(Boolean);

const catalogVersion = createHash("sha256")
  .update(JSON.stringify(articles))
  .digest("hex")
  .slice(0, 12);

const output =
  "// GENERATED by website/scripts/generate-help-article-catalog.mjs. Do not edit by hand.\n" +
  "// Regenerate after any help-article add, removal or retitle, then redeploy (#3275).\n" +
  `export default ${JSON.stringify({ catalogVersion, articles }, null, 2)};\n`;

writeFileSync(outFile, output);
console.log(`wrote ${articles.length} articles, catalogVersion ${catalogVersion}, to ${outFile}`);
