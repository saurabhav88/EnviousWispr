def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if index.html is out of date")
    args = parser.parse_args()
    try:
        page = render()
    except (AtlasError, OSError, KeyError) as error:
        print(f"build-atlas-index: {error}", file=sys.stderr)
        return 2
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else None
        if current != page:
            print("build-atlas-index: design/atlas/index.html is out of date; run "
                  "python3 scripts/design/build-atlas-index.py", file=sys.stderr)
            return 1
        print("build-atlas-index: up to date")
        return 0
    OUTPUT.write_text(page, encoding="utf-8")
    print(f"build-atlas-index: wrote {OUTPUT.relative_to(REPO)} ({len(page)} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
