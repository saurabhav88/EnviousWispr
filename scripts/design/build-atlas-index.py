#!/usr/bin/env python3
"""Build design/atlas/index.html, the screen atlas gallery (#4506).

The page opens straight from disk (file://), where browsers refuse fetch(), so this
script embeds everything the page needs except the CSS and the pictures, which it
links by relative path:
- atlas.json (the picture list),
- every part between `<!-- part: id | title | swift owner | picture id -->` and
  `<!-- /part -->` in design/atlas/parts/*.html, written into the page as static
  markup and as escaped copyable text (the script never turns data into HTML).

Usage:
  python3 scripts/design/build-atlas-index.py           # write index.html
  python3 scripts/design/build-atlas-index.py --check   # exit 1 if index.html is out of date

Fails (exit 2) on: unreadable or invalid atlas.json, a part marker without its end,
a duplicate part id, or a part naming a picture id atlas.json does not list (`none` marks a part drawn
from its Swift source because no picture shows it).
"""

from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
ATLAS = REPO / "design/atlas"
OUTPUT = ATLAS / "index.html"
PART = re.compile(
    r"<!-- part: (?P<id>[a-z0-9-]+) \| (?P<title>[^|]+?) \| (?P<swift>[^|]+?) \| (?P<picture>[A-Za-z0-9-]+) -->\n"
    r"(?P<html>.*?)\n<!-- /part -->",
    re.DOTALL)


class AtlasError(Exception):
    pass


def load_parts(picture_ids: set[str]) -> list[dict]:
    parts, seen = [], set()
    for path in sorted((ATLAS / "parts").glob("*.html")):
        text = path.read_text(encoding="utf-8")
        if text.count("<!-- part:") != text.count("<!-- /part -->"):
            raise AtlasError(f"{path.name}: a part marker has no matching <!-- /part -->")
        for match in PART.finditer(text):
            part = {key: match.group(key).strip() for key in ("id", "title", "swift", "picture", "html")}
            if part["id"] in seen:
                raise AtlasError(f"{path.name}: part id {part['id']} repeats")
            if part["picture"] != "none" and part["picture"] not in picture_ids:
                raise AtlasError(f"{path.name}: part {part['id']} names unknown picture {part['picture']}")
            seen.add(part["id"])
            part["file"] = f"parts/{path.name}"
            parts.append(part)
        if text.count("<!-- part:") != len([m for m in PART.finditer(text)]):
            raise AtlasError(f"{path.name}: a part marker is malformed")
    return parts


def render() -> str:
    try:
        atlas = json.loads((ATLAS / "atlas.json").read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as error:
        raise AtlasError(f"atlas.json: {error}") from error
    pictures = atlas["pictures"]
    parts = load_parts({p["id"] for p in pictures})
    # Parts are written into the page as static markup (live) and as escaped text (copy), so the
    # script never turns data into HTML. Only the picture list travels as JSON.
    data = json.dumps({"pictures": pictures}, indent=1, ensure_ascii=False)
    data = data.replace("</", "<\\/")
    return TEMPLATE.replace("/*ATLAS_DATA*/", data).replace("<!--PARTS-->", "\n".join(map(part_markup, parts)))


def part_markup(part: dict) -> str:
    e = html.escape
    if part["picture"] == "none":
        shot = ('<div class="shot meta">No app picture shows this part; it is drawn from its source ('
                + e(part["swift"]) + ').</div>')
    else:
        shot = f'<div class="shot"><img data-picture="{e(part["picture"])}" alt="{e(part["picture"])}" loading="lazy"></div>'
    search = e(" ".join((part["id"], part["title"], part["swift"])).lower())
    return (
        f'<section class="item" data-search="{search}">\n'
        f'  <h3>{e(part["title"])}</h3>\n'
        f'  <div class="meta">{e(part["swift"])} \u00b7 {e(part["file"])} \u00b7 picture {e(part["picture"])}</div>\n'
        f'  <div class="pair"><div><div class="label">HTML part</div><div class="live">\n{part["html"]}\n</div></div>'
        f'<div><div class="label">App picture</div>{shot}</div></div>\n'
        f'  <div style="display:flex;gap:8px"><button class="ew-btn" data-copy>Copy snippet</button>'
        f'<button class="ew-btn ew-btn--quiet" data-show>Show HTML</button></div>\n'
        f'  <pre class="meta hidden">{e(part["html"])}</pre>\n'
        f'</section>')


